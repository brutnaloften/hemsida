/**
 * Promotion of manifesto candidates that carry no agreement link (any party, any term).
 * Pure transformation: no agreement evidence is added, `vague` promises become `not_assessable`,
 * everything else stays as extracted (`unassessed`, `evidence: []`). Nothing here is keyed to a
 * party or term: the party comes from the source record, the id prefix from `idPrefix`.
 */

import type { ManifestoEntry } from './manifesto-extract.ts';
import { VAGUE_REASONING } from './manifesto-promote.ts';
import { promiseSchema, type PromiseRecord } from './schema.ts';

type Party = PromiseRecord['parties'][number];

export interface PromoteOptions {
  /** Require this role for the party (the 2022 opposition parties pass 'opposition'). */
  requireRole?: 'government' | 'support' | 'opposition';
}

export function promoteManifesto(
  entries: readonly ManifestoEntry[],
  party: Party,
  options: PromoteOptions = {},
): PromiseRecord[] {
  const out = entries.map((e) => {
    if (e.link) throw new Error(`${e.promise.id} has an agreement link; use the linked promotion`);
    const p = structuredClone(e.promise);
    if (!p.parties.includes(party)) throw new Error(`${p.id}: ${party} is not a promise party`);
    if (options.requireRole && p.roles[party] !== options.requireRole) {
      throw new Error(`${p.id}: ${party} is not ${options.requireRole}`);
    }
    if (p.evidence.length > 0) throw new Error(`${p.id}: candidate has evidence`);
    if (p.type === 'vague') {
      p.verdict = {
        value: 'not_assessable',
        reasoning: VAGUE_REASONING,
        date: p.verdict.date,
        history: [],
      };
    }
    return promiseSchema.parse(p);
  });
  const ids = out.map((p) => p.id);
  if (new Set(ids).size !== ids.length) throw new Error('Promoted ids are not unique');
  return out;
}

/** As `promoteManifesto`, but the party must be in opposition (the 2022 opposition parties). */
export function promoteOpposition(
  entries: readonly ManifestoEntry[],
  party: Party,
): PromiseRecord[] {
  return promoteManifesto(entries, party, { requireRole: 'opposition' });
}

/** Audit doc for a generic promotion run (docs/manifesto-promotion-map-<party>.md). */
export function renderPromotionMap(args: {
  title: string;
  sourceId: string;
  term: string;
  party: string;
  prefix: string;
  entries: readonly ManifestoEntry[];
  promises: readonly PromiseRecord[];
}): string {
  const { title, sourceId, term, party, prefix, entries, promises } = args;
  const vague = promises.filter((p) => p.type === 'vague');
  const bySection = new Map<string, string[]>();
  entries.forEach((e, i) => {
    const list = bySection.get(e.section) ?? [];
    list.push(promises[i]!.id);
    bySection.set(e.section, list);
  });
  return [
    `# ${title} promotion map`,
    '',
    `Generated by \`tools/promote-opposition-manifesto.ts --source ${sourceId} --term ${term}\`; do not edit by hand. Candidates in \`src/data/${term}/candidates/${sourceId}.json\` are kept as the record of the extraction.`,
    '',
    `${entries.length} candidates became ${promises.length} promises in \`src/data/${term}/promises/\` (\`${prefix}*.json\`). The promises of ${party} carry no agreement evidence (\`evidence: []\`). Review was done by AI in place of a human reviewer, as decided for seeding. Verdicts are unchanged: every promise is \`unassessed\`, except the ${vague.length} \`vague\` ones, which are \`not_assessable\`.`,
    '',
    '## Vague promises',
    '',
    ...vague.map((p) => `- \`${p.id}\``),
    '',
    '## Promises by manifesto section',
    '',
    ...[...bySection].flatMap(([section, ids]) => [
      `### ${section} (${ids.length})`,
      '',
      ...ids.map((id) => `- \`${id}\``),
      '',
    ]),
  ].join('\n');
}
