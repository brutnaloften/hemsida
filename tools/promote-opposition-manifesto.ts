/**
 * Promote reviewed manifesto candidates of a party that is not in the Tidö agreement (opposition)
 * to promise files. No agreement evidence is added: the promise keeps `evidence: []`. `vague`
 * promises become `not_assessable`, as for L, M and KD; everything else stays `unassessed`.
 *   node --experimental-strip-types tools/promote-opposition-manifesto.ts --source valmanifest-2022-s
 * Writes src/data/2022-2026/promises/<id-prefix>*.json and docs/manifesto-promotion-map-<party>.md.
 * Idempotent: rewrites the same files and removes stale promise files with the same id prefix.
 * Party-parametric counterpart to the Tidö-linked tool (see bead hemsida-5ag).
 */

import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { loadJson, writeJson } from './lib/json.ts';
import { idPrefix, manifestoEntrySchema } from './lib/manifesto-extract.ts';
import { promoteOpposition } from './lib/opposition-promote.ts';
import { sourceSchema } from './lib/schema.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { values } = parseArgs({
  options: { source: { type: 'string' }, term: { type: 'string', default: '2022-2026' } },
});
if (!values.source) throw new Error('--source <source-id> is required');

const source = sourceSchema.parse(
  loadJson(resolve(root, 'src/data/sources', `${values.source}.json`)),
);
if (source.parties.length !== 1) throw new Error('source must have exactly one party');
const party = source.parties[0]!;
const prefix = `${idPrefix(source)}-`;
const termDir = resolve(root, 'src/data', values.term!);
const entries = manifestoEntrySchema
  .array()
  .parse(loadJson(resolve(termDir, 'candidates', `${source.id}.json`)));

const promises = promoteOpposition(entries, party);

const outDir = resolve(termDir, 'promises');
mkdirSync(outDir, { recursive: true });
for (const f of readdirSync(outDir)) {
  if (f.startsWith(prefix) && f.endsWith('.json')) rmSync(resolve(outDir, f));
}
for (const p of promises) writeJson(resolve(outDir, `${p.id}.json`), p);

const vague = promises.filter((p) => p.type === 'vague');
const bySection = new Map<string, string[]>();
entries.forEach((e, i) => {
  const list = bySection.get(e.section) ?? [];
  list.push(promises[i]!.id);
  bySection.set(e.section, list);
});
const doc = [
  `# ${source.title} promotion map`,
  '',
  `Generated by \`tools/promote-opposition-manifesto.ts --source ${source.id}\`; do not edit by hand. Candidates in \`src/data/${values.term}/candidates/${source.id}.json\` are kept as the record of the extraction.`,
  '',
  `${entries.length} candidates became ${promises.length} promises in \`src/data/${values.term}/promises/\` (\`${prefix}*.json\`). ${party} is in opposition and not party to the Tidö agreement, so the promises carry no agreement evidence (\`evidence: []\`). Review was done by AI in place of a human reviewer, as decided for seeding. Verdicts are unchanged: every promise is \`unassessed\`, except the ${vague.length} \`vague\` ones, which are \`not_assessable\`.`,
  '',
  '## Vague promises',
  '',
  ...vague.map((p) => `- \`${p.id}\``),
  '',
  '## Promises by manifesto section',
  '',
  ...[...bySection].flatMap(([section, ids]) => [
    `### ${section} (${ids.length})`,
    '',
    ...ids.map((id) => `- \`${id}\``),
    '',
  ]),
];
writeFileSync(
  resolve(root, 'docs', `manifesto-promotion-map-${party.toLowerCase()}.md`),
  doc.join('\n'),
);
console.log(`Wrote ${promises.length} promises (${vague.length} not_assessable).`);
